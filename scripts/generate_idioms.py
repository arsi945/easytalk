#!/usr/bin/env python3
"""One reviewed idiom collection shared by iOS and macOS. No runtime downloads."""
import argparse, json, pathlib, sys
root=pathlib.Path(__file__).resolve().parent.parent
catalog=json.loads((root/'glossary/idioms-en-ru.json').read_text())
items=catalog['items']
assert catalog['schema_version']==1
assert len(items)>=60
assert len({x['id'] for x in items})==len(items)
assert len({x['term'].casefold() for x in items})==len(items)
assert [x['id'] for x in items[:12]]==[f'second-skill.i{i}' for i in range(1,13)]
fields=['id','term','meaning','example','note','category','source']
for x in items:
 assert all(isinstance(x[f],str) and x[f].strip() for f in fields)
 assert isinstance(x['examples'], list) and 2 <= len(x['examples']) <= 3 and len(set(x['examples'])) == len(x['examples'])
 assert all(isinstance(t, str) and 0 < len(t) <= 320 for t in x['examples'])
 assert x['verified']!='pending'
 assert x['source'].startswith(('https://','second-skill.zip'))
quote=lambda x:json.dumps(x,ensure_ascii=False)
header='''// Generated by scripts/generate_idioms.py from glossary/idioms-en-ru.json.
// See glossary/LICENSE.md and docs/IDIOMS_SOURCES.md for provenance.
import Foundation

public struct IdiomEntry: Codable, Identifiable, Equatable {
'''
header+=''.join(f'    public let {f}: String\n' for f in fields)
header+='    public let examples: [String]\n'
header+='    public init('+', '.join(f'{f}: String' for f in fields)+', examples: [String]? = nil) {\n'
header+=''.join(f'        self.{f} = {f}\n' for f in fields)+'        self.examples = examples ?? [example]\n    }\n}\n\npublic enum IdiomCatalog {\n'
header+='    public static let version = '+quote(catalog['catalog_version'])+'\n'
header+='    public static let all: [IdiomEntry] = [\n'
header+=''.join('        IdiomEntry('+', '.join(f'{f}: {quote(x[f])}' for f in fields)+', examples: '+quote(x['examples'])+'),\n' for x in items)
header+='    ]\n}\n'
target=root/'Sources/EasyTalkCore/IdiomCatalog.swift'
if '--check' in sys.argv:
 if not target.exists() or target.read_text()!=header:sys.exit('Generated idioms out of date; run scripts/generate_idioms.py')
 print(f'idioms: {len(items)} reviewed entries; generated Swift matches JSON')
else:
 target.write_text(header); print(f'generated {target}: {len(items)} entries')
